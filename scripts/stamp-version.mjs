import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const version = (await readFile(path.join(root, 'VERSION'), 'utf8')).trim();
if (!/^\d+\.\d+\.\d+(?:-[\w.-]+)?$/.test(version)) throw new Error('Invalid VERSION');
const assets = ['public/index.html', 'public/style.css', 'public/game.js', 'public/wildlife.js', 'public/favicon.svg'];
const hash = createHash('sha256').update(version);
for (const asset of assets) {
  hash.update(asset).update(await readFile(path.join(root, asset)));
}
const build = hash.digest('hex').slice(0, 8);
let commit = null, modified = null;
try {
  commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  modified = Boolean(execFileSync('git', ['status', '--porcelain', '--untracked-files=all', '--', 'VERSION', ...assets], { cwd: root, encoding: 'utf8' }).trim());
} catch {
  commit = null;
  modified = null;
  // Source archives may not include Git; the content fingerprint still identifies the build.
}
const label = `v${version} · build ${build}${commit ? ` · ${commit.slice(0, 7)}${modified ? ' (modified)' : ''}` : ''}`;
const title = `Agromate ${version}\nBuild: ${build}${commit ? `\nGit: ${commit}${modified ? '\nIncludes uncommitted changes' : ''}` : '\nGit metadata unavailable'}`;
const metadata = { version, build, commit, modified };
const script = `// Generated by node scripts/stamp-version.mjs. Regenerate before publishing.\n(() => {\n  const badge = document.getElementById('build-version');\n  if (!badge) return;\n  badge.textContent = ${JSON.stringify(label)};\n  badge.title = ${JSON.stringify(title)};\n  badge.dataset.build = ${JSON.stringify(build)};\n})();\n`;
await writeFile(path.join(root, 'public/version.js'), script);
console.log(JSON.stringify(metadata));
